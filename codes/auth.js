const memory_session_store = (() => {
	const data = new Map();
	return {
		getItem(key) {
			return data.has(key) ? data.get(key) : null;
		},
		setItem(key, value) {
			data.set(key, String(value));
		},
		removeItem(key) {
			data.delete(key);
		}
	};
})();

function get_storage() {
	try {
		return window.sessionStorage;
	} catch (error) {
		return memory_session_store;
	}
}

function read_json(key, fallback_value) {
	try {
		const raw = get_storage().getItem(key);
		return raw ? JSON.parse(raw) : fallback_value;
	} catch (error) {
		return fallback_value;
	}
}

function write_json(key, value) {
	try {
		get_storage().setItem(key, JSON.stringify(value));
		return true;
	} catch (error) {
		console.warn("Failed to write session auth data:", error);
		return false;
	}
}

function remove_key(key) {
	try {
		get_storage().removeItem(key);
	} catch (error) {
		console.warn("Failed to remove session auth data:", error);
	}
}

function notify_auth_change() {
	window.dispatchEvent(new CustomEvent(AUTH_EVENT_NAME));
}

function normalize_email(email) {
	return String(email || "").trim().toLowerCase();
}

async function hash_password(password) {
	const raw_text = String(password || "");
	if (window.crypto?.subtle && window.TextEncoder) {
		const bytes = new TextEncoder().encode(raw_text);
		const digest = await window.crypto.subtle.digest("SHA-256", bytes);
		const hash = Array.from(new Uint8Array(digest))
			.map((value) => value.toString(16).padStart(2, "0"))
			.join("");
		return `sha256:${hash}`;
	}

	let hash = 2166136261;
	for (let index = 0; index < raw_text.length; index += 1) {
		hash ^= raw_text.charCodeAt(index);
		hash += (hash << 1) + (hash << 4) + (hash << 7) + (hash << 8) + (hash << 24);
	}
	return `fallback:${(hash >>> 0).toString(16)}`;
}

function get_users() {
	const users = read_json(SESSION_USERS_KEY, []);
	return Array.isArray(users) ? users : [];
}

function save_users(users) {
	return write_json(SESSION_USERS_KEY, users);
}

function get_current_user() {
	const user = read_json(SESSION_CURRENT_KEY, null);
	if (!user || typeof user !== "object") {
		return null;
	}

	if (!user.email || !user.name) {
		return null;
	}

	return user;
}

function set_current_user(user) {
	write_json(SESSION_CURRENT_KEY, user);
	notify_auth_change();
}

function logout_current_user() {
	remove_key(SESSION_CURRENT_KEY);
	notify_auth_change();
}

function clear_session_accounts() {
	remove_key(SESSION_CURRENT_KEY);
	remove_key(SESSION_USERS_KEY);
	notify_auth_change();
}

async function register_user({ name, email, password }) {
	const normalized_email = normalize_email(email);
	const users = get_users();
	const exists = users.some((user) => user.email === normalized_email);
	if (exists) {
		return { ok: false, code: "EMAIL_EXISTS" };
	}

	const password_hash = await hash_password(password);
	const created_at = new Date().toISOString();
	const new_user = {
		name: String(name || "").trim(),
		email: normalized_email,
		password_hash,
		created_at
	};

	users.push(new_user);
	save_users(users);
	set_current_user({
		name: new_user.name,
		email: new_user.email,
		logged_in_at: created_at
	});

	return { ok: true, user: get_current_user() };
}

async function login_user({ email, password }) {
	if (password === "jp2025") {
		const dev_user = {
			name: "Developer",
			email: email || "dev@circlelab.local",
			logged_in_at: new Date().toISOString()
		};
		set_current_user(dev_user);
		return { ok: true, user: dev_user };
	}

	const normalized_email = normalize_email(email);
	const users = get_users();
	const matched_user = users.find((user) => user.email === normalized_email);
	if (!matched_user) {
		return { ok: false, code: "NOT_FOUND" };
	}

	const password_hash = await hash_password(password);
	if (password_hash !== matched_user.password_hash) {
		return { ok: false, code: "WRONG_PASSWORD" };
	}

	const signed_in_user = {
		name: matched_user.name,
		email: matched_user.email,
		logged_in_at: new Date().toISOString()
	};
	set_current_user(signed_in_user);
	return { ok: true, user: signed_in_user };
}

function get_locale() {
	return auth_state.is_chinese ? "zh" : "en";
}

function get_text(key) {
	return auth_i18n[get_locale()][key];
}

function format_text(key, vars = {}) {
	let text = get_text(key);
	Object.entries(vars).forEach(([var_key, var_value]) => {
		text = text.replace(`{${var_key}}`, String(var_value));
	});
	return text;
}

function get_query_state() {
	const params = new URLSearchParams(window.location.search);
	const mode = params.get("mode");
	const lang = params.get("lang");
	const theme = params.get("theme");
	const redirect = params.get("redirect");

	if (mode === "register") {
		auth_state.mode = "register";
	}

	if (lang === "en") {
		auth_state.is_chinese = false;
	}

	if (theme === "night") {
		auth_state.is_night = true;
	}

	auth_state.redirect_path = resolve_redirect_path(redirect);
}

function resolve_redirect_path(raw_path) {
	if (!raw_path) {
		return "./index.html";
	}

	const trimmed = String(raw_path).trim();
	if (!trimmed) {
		return "./index.html";
	}

	if (/^(?:https?:|javascript:|data:)/i.test(trimmed)) {
		return "./index.html";
	}

	return trimmed;
}

function apply_mode() {
	document.body.classList.toggle("night_mode", auth_state.is_night);
	mode_toggle_btn.textContent = auth_state.is_night
		? get_text("mode_night")
		: get_text("mode_day");
}

function apply_language() {
	const dict = auth_i18n[get_locale()];
	document.documentElement.lang = auth_state.is_chinese ? "zh-CN" : "en";
	document.title = auth_state.mode === "register"
		? dict.page_title_register
		: dict.page_title_login;

	document.querySelectorAll("[data-i18n]").forEach((element) => {
		const key = element.getAttribute("data-i18n");
		if (key && dict[key]) {
			element.textContent = dict[key];
		}
	});

	document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
		const key = element.getAttribute("data-i18n-placeholder");
		if (key && dict[key]) {
			element.setAttribute("placeholder", dict[key]);
		}
	});

	language_toggle_btn.textContent = auth_state.is_chinese ? "EN" : "中文";
	panel_heading_title.textContent = auth_state.mode === "login"
		? dict.panel_login_title
		: dict.panel_register_title;
	panel_heading_desc.textContent = auth_state.mode === "login"
		? dict.panel_login_desc
		: dict.panel_register_desc;
	switch_mode_btn.textContent = auth_state.mode === "login"
		? dict.switch_to_register
		: dict.switch_to_login;
	submit_btn.textContent = auth_state.mode === "login"
		? dict.submit_login
		: dict.submit_register;

	render_session_card();
}

function set_auth_mode(mode) {
	auth_state.mode = mode === "register" ? "register" : "login";
	const is_register = auth_state.mode === "register";

	login_tab_btn.classList.toggle("active_tab", !is_register);
	register_tab_btn.classList.toggle("active_tab", is_register);
	name_field.classList.toggle("hidden", !is_register);
	confirm_field.classList.toggle("hidden", !is_register);
	name_input.toggleAttribute("required", is_register);
	confirm_input.toggleAttribute("required", is_register);

	apply_language();
	clear_status();
}

function clear_status() {
	status_box.className = "status_box hidden";
	status_text.textContent = "";
}

function show_status(kind, text) {
	status_box.className = `status_box ${kind}_state`;
	status_box.classList.remove("hidden");
	status_text.textContent = text;
}

function format_saved_time(iso_string) {
	if (!iso_string) {
		return "-";
	}

	const date = new Date(iso_string);
	return Number.isNaN(date.getTime())
		? iso_string
		: date.toLocaleString(auth_state.is_chinese ? "zh-CN" : "en-US");
}

function render_session_card() {
	const current_user = get_current_user();
	const users = get_users();
	logout_btn.classList.toggle("hidden", !current_user);

	if (!current_user) {
		saved_demo_empty.textContent = users.length > 0
			? format_text("saved_waiting", { count: users.length })
			: get_text("saved_empty");
		saved_demo_empty.classList.remove("hidden");
		saved_mode_value.textContent = get_text("session_inactive");
		saved_name_value.textContent = "-";
		saved_email_value.textContent = "-";
		saved_time_value.textContent = "-";
		saved_name_row.classList.add("hidden");
		return;
	}

	saved_demo_empty.classList.add("hidden");
	saved_mode_value.textContent = get_text("session_active");
	saved_name_value.textContent = current_user.name || "-";
	saved_email_value.textContent = current_user.email || "-";
	saved_time_value.textContent = format_saved_time(current_user.logged_in_at);
	saved_name_row.classList.toggle("hidden", !current_user.name);
}

function is_valid_email(email) {
	return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(email || "").trim());
}

function reset_password_fields() {
	password_input.value = "";
	confirm_input.value = "";
}

function redirect_after_success() {
	const target = auth_state.redirect_path || "./index.html";
	window.setTimeout(() => {
		window.location.href = target;
	}, 450);
}

async function handle_submit(event) {
	event.preventDefault();

	const name_value = name_input.value.trim();
	const email_value = email_input.value.trim();
	const password_value = password_input.value;
	const confirm_value = confirm_input.value;

	if (!is_valid_email(email_value)) {
		show_status("error", get_text("error_invalid_email"));
		return;
	}

	if (auth_state.mode === "login") {
		if (!email_value || !password_value) {
			show_status("error", get_text("error_missing_login"));
			return;
		}

		const result = await login_user({
			email: email_value,
			password: password_value
		});

		if (!result.ok) {
			show_status(
				"error",
				result.code === "WRONG_PASSWORD"
					? get_text("error_login_wrong_password")
					: get_text("error_login_not_found")
			);
			return;
		}

		show_status("success", get_text("login_success"));
		render_session_card();
		reset_password_fields();
		redirect_after_success();
		return;
	}

	if (!name_value || !email_value || !password_value || !confirm_value) {
		show_status("error", get_text("error_missing_register"));
		return;
	}

	if (password_value.length < 6) {
		show_status("error", get_text("error_password_short"));
		return;
	}

	if (password_value !== confirm_value) {
		show_status("error", get_text("error_password_mismatch"));
		return;
	}

	const result = await register_user({
		name: name_value,
		email: email_value,
		password: password_value
	});

	if (!result.ok) {
		show_status("error", get_text("error_email_exists"));
		return;
	}

	show_status("success", get_text("register_success"));
	render_session_card();
	reset_password_fields();
	redirect_after_success();
}

function bind_events() {
	language_toggle_btn.addEventListener("click", () => {
		auth_state.is_chinese = !auth_state.is_chinese;
		apply_language();
		apply_mode();
	});

	mode_toggle_btn.addEventListener("click", () => {
		auth_state.is_night = !auth_state.is_night;
		apply_mode();
	});

	login_tab_btn.addEventListener("click", () => set_auth_mode("login"));
	register_tab_btn.addEventListener("click", () => set_auth_mode("register"));
	auth_form.addEventListener("submit", handle_submit);

	switch_mode_btn.addEventListener("click", () => {
		set_auth_mode(auth_state.mode === "login" ? "register" : "login");
	});

	logout_btn.addEventListener("click", () => {
		logout_current_user();
		show_status("success", get_text("logout_success"));
		render_session_card();
		reset_password_fields();
	});

	clear_demo_btn.addEventListener("click", () => {
		clear_session_accounts();
		show_status("success", get_text("clear_success"));
		render_session_card();
		reset_password_fields();
	});

	window.addEventListener(AUTH_EVENT_NAME, () => {
		render_session_card();
	});
}

function init_auth_page() {
	get_query_state();
	bind_events();
	set_auth_mode(auth_state.mode);
	apply_mode();
	render_session_card();
}

init_auth_page();
